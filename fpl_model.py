def _fetch_json(url: str, timeout: int = 20) -> Any:
    r = requests.get(url, timeout=timeout)
    r.raise_for_status()
    return r.json()


def load_csv(filename: str) -> pd.DataFrame:
    url = GITHUB_BASE + filename
    try:
        return pd.read_csv(url, encoding="utf-8")
    except UnicodeDecodeError:
        return pd.read_csv(url, encoding="latin1")


@lru_cache(maxsize=1)
def get_gw_context() -> Dict[str, Any]:
    """
    Computes current GW + derived vars (cached per process).
    No network calls at import time.
    """
    url0 = "https://fantasy.premierleague.com/api/fixtures?future=1"
    js0 = _fetch_json(url0)
    nxt = pd.DataFrame(js0)[["event"]]
    var_gw = int(pd.to_numeric(nxt["event"], errors="coerce").min())

    ctx = {
        "VAR_GW": var_gw,
        "VAR_GW0": var_gw - 1,  # last completed
        "VAR_GW_LY": 38 - 1,
        "VGW_NAME_1": f"gw{var_gw}",
        "VGW_NAME_2": f"gw{var_gw+1}",
        "VGW_NAME_3": f"gw{var_gw+2}",
        "VGW_NAME_4": f"gw{var_gw+3}",
        "VGW_NAME_5": f"gw{var_gw+4}",
        "VGW_NAME_6": f"gw{var_gw+5}",
    }
    return ctx


