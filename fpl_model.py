def _pick_starting_xi_for_week(team_df: pd.DataFrame, week_col: str) -> List[int]:
    """
    Heuristic: pick best XI by points for that week subject to legal formation.
    Returns list of row indices for starters (within team_df).
    """
    df = team_df.copy()
    df[week_col] = pd.to_numeric(df[week_col], errors="coerce").fillna(0)

    # must include 1 GKP
    starters = []
    gk = df[df["pos"] == "GKP"].sort_values(week_col, ascending=False).head(1)
    starters += gk.index.tolist()

    remaining = df.drop(index=starters)

    # choose outfield 10 with formation constraints:
    # DEF 3-5, MID 2-5, FWD 1-3
    # greedy: try all feasible splits, pick best total
    best = None
    out = remaining.copy()

    def top_n(pos: str, n: int) -> pd.DataFrame:
        return out[out["pos"] == pos].sort_values(week_col, ascending=False).head(n)

    for n_def in range(3, 6):
        for n_mid in range(2, 6):
            for n_fwd in range(1, 4):
                if n_def + n_mid + n_fwd != 10:
                    continue
                sel = pd.concat([top_n("DEF", n_def), top_n("MID", n_mid), top_n("FWD", n_fwd)])
                if len(sel) != 10:
                    continue
                total = sel[week_col].sum() + df.loc[starters, week_col].sum()
                if best is None or total > best[0]:
                    best = (total, starters + sel.index.tolist())

    if best is None:
        # fallback: just top 10 outfielders
        sel = out.sort_values(week_col, ascending=False).head(10)
        return starters + sel.index.tolist()

    return best[1]


def optimise_squad(
    pool: pd.DataFrame,
    budget: int = 1000,
    transfers: int = 0,
    current_ids: Optional[List[int]] = None,
    exclude_names: Optional[List[str]] = None,
    exclude_teams: Optional[List[str]] = None,
    include_names: Optional[List[str]] = None,
    optimisation_mode: str = "next_6_gw",
    ctx: Optional[Dict[str, Any]] = None,
) -> Tuple[pd.DataFrame, List[str], List[int]]:
    """
    Returns: final_team_df, current_names, current_ids
    """
    ctx = ctx or get_gw_context()
    df = pool.copy()

    exclude_names = [x.strip() for x in (exclude_names or []) if x and str(x).strip()]
    exclude_teams = [x.strip() for x in (exclude_teams or []) if x and str(x).strip()]
    include_names = [x.strip() for x in (include_names or []) if x and str(x).strip()]

    # apply excludes
    if exclude_names:
        df = df[~df["name"].isin(exclude_names)]
    if exclude_teams:
        df = df[~df["team"].isin(exclude_teams)]

    # objective points column
    if optimisation_mode == "gw1_only":
        obj_col = ctx["VGW_NAME_1"]
        df[obj_col] = pd.to_numeric(df[obj_col], errors="coerce").fillna(0)
        df["obj_points"] = df[obj_col]
    else:
        df["obj_points"] = pd.to_numeric(df["predicted_points"], errors="coerce").fillna(0)

    # current squad markers
    current_ids = current_ids or []
    current_id_set = set(current_ids)
    df["is_current"] = df["element"].isin(current_id_set).astype(int)

    # LP
    prob = pulp.LpProblem("FPL_Squad", pulp.LpMaximize)
    x = {int(r.element): pulp.LpVariable(f"x_{int(r.element)}", 0, 1, cat="Binary") for r in df.itertuples(index=False)}

    # maximise objective
    prob += pulp.lpSum([x[int(r.element)] * float(r.obj_points) for r in df.itertuples(index=False)])

    # squad size
    prob += pulp.lpSum([x[e] for e in x]) == 15

    # budget
    prob += pulp.lpSum([x[int(r.element)] * float(r.cost) for r in df.itertuples(index=False)]) <= float(budget)

    # position counts
    def _count_pos(pos: str) -> pulp.LpAffineExpression:
        return pulp.lpSum([x[int(r.element)] for r in df.itertuples(index=False) if r.pos == pos])

    prob += _count_pos("GKP") == 2
    prob += _count_pos("DEF") == 5
    prob += _count_pos("MID") == 5
    prob += _count_pos("FWD") == 3

    # max 3 per team
    for team in df["team"].unique():
        prob += pulp.lpSum([x[int(r.element)] for r in df.itertuples(index=False) if r.team == team]) <= 3

    # must-includes (by name)
    if include_names:
        name_to_element = df.groupby("name")["element"].apply(list).to_dict()
        for nm in include_names:
            els = name_to_element.get(nm)
            if els:
                prob += pulp.lpSum([x[int(e)] for e in els]) >= 1

    # transfers constraint (simple “keep at least 15 - transfers”)
    if current_ids and transfers is not None and transfers >= 0:
        keep_min = max(0, 15 - int(transfers))
        prob += pulp.lpSum([x[int(r.element)] for r in df.itertuples(index=False) if int(r.element) in current_id_set]) >= keep_min

    # solve
    prob.solve(pulp.PULP_CBC_CMD(msg=False))
    if pulp.LpStatus[prob.status] != "Optimal":
        raise ValueError(f"Optimiser failed: {pulp.LpStatus[prob.status]}")

    chosen = [e for e, var in x.items() if var.value() == 1]
    team_df = df[df["element"].isin(chosen)].copy()

    # attach starting weeks
    week_cols = [ctx["VGW_NAME_1"], ctx["VGW_NAME_2"], ctx["VGW_NAME_3"], ctx["VGW_NAME_4"], ctx["VGW_NAME_5"], ctx["VGW_NAME_6"]]
    existing_week_cols = [c for c in week_cols if c in team_df.columns]

    starters_map = {i: [] for i in team_df.index}
    for w in existing_week_cols:
        starter_idx = _pick_starting_xi_for_week(team_df, w)
        for idx in starter_idx:
            starters_map[idx].append(w)

    team_df["starting_weeks"] = [" ,".join(starters_map[i]).replace(" ,", ",") for i in team_df.index]

    # display ordering
    pos_order = {"GKP": 0, "DEF": 1, "MID": 2, "FWD": 3}
    team_df["pos_sort"] = team_df["pos"].map(pos_order).fillna(99).astype(int)
    team_df = team_df.sort_values(["pos_sort", "obj_points"], ascending=[True, False]).drop(columns=["pos_sort"])

    current_names = sorted(df[df["element"].isin(current_id_set)]["name"].unique().tolist()) if current_ids else []
    return team_df.reset_index(drop=True), current_names, current_ids


